package silver

import java.io.BufferedReader
import java.io.InputStreamReader
import java.util.StringTokenizer

// - 문제 | 차세대 영농인 한나는 강원도 고랭지에서 유기농 배추를 재배하기로 하였다. 농약을 쓰지 않고 배추를 재배하려면 배추를 해충으로부터 보호하는 것이 중요하기 때문에,
//      한나는 해충 방지에 효과적인 배추흰지렁이를 구입하기로 결심한다. 이 지렁이는 배추근처에 서식하며 해충을 잡아 먹음으로써 배추를 보호한다.
//      특히, 어떤 배추에 배추흰지렁이가 한 마리라도 살고 있으면 이 지렁이는 인접한 다른 배추로 이동할 수 있어, 그 배추들 역시 해충으로부터 보호받을 수 있다.
//      한 배추의 상하좌우 네 방향에 다른 배추가 위치한 경우에 서로 인접해있는 것이다.
//      한나가 배추를 재배하는 땅은 고르지 못해서 배추를 군데군데 심어 놓았다. 배추들이 모여있는 곳에는 배추흰지렁이가 한 마리만 있으면 되므로 서로 인접해있는
//      배추들이 몇 군데에 퍼져있는지 조사하면 총 몇 마리의 지렁이가 필요한지 알 수 있다. 예를 들어 배추밭이 아래와 같이 구성되어 있으면 최소 5마리의 배추흰지렁이가 필요하다.
//      0은 배추가 심어져 있지 않은 땅이고, 1은 배추가 심어져 있는 땅을 나타낸다.

// - 입력 | 입력의 첫 줄에는 테스트 케이스의 개수 T가 주어진다. 그 다음 줄부터 각각의 테스트 케이스에 대해 첫째 줄에는 배추를 심은 배추밭의
//      가로길이 M(1 ≤ M ≤ 50)과 세로길이 N(1 ≤ N ≤ 50), 그리고 배추가 심어져 있는 위치의 개수 K(1 ≤ K ≤ 2500)이 주어진다.
//      그 다음 K줄에는 배추의 위치 X(0 ≤ X ≤ M-1), Y(0 ≤ Y ≤ N-1)가 주어진다. 두 배추의 위치가 같은 경우는 없다.

// - 출력 | 각 테스트 케이스에 대해 필요한 최소의 배추흰지렁이 마리 수를 출력한다.

// 이동할수 있는 전역변수 각각 선언 dx,와 dy
// [1. 방향 지시자 설정 (전역 변수)]
// DFS 함수 안에서 상하좌우를 탐색할 때 사용할 좌표 변화량입니다.
// 전역 변수로 빼둔 이유는 main 함수와 dfs 함수 모두에서 접근하기 쉽고, 메모리 낭비를 줄이기 위함입니다.
// dx: x축(행) 이동량 -> 0(변화없음), 0(변화없음), -1(위/왼쪽), 1(아래/오른쪽)
// dy: y축(열) 이동량 -> -1(왼쪽/위), 1(오른쪽/아래), 0(변화없음), 0(변화없음)
// ※ 인덱스 0끼리, 1끼리 짝을 지어 (0,-1), (0,1), (-1,0), (1,0) 이렇게 4방향을 만듭니다.
val dx = intArrayOf(0, 0, -1, 1)
val dy = intArrayOf(-1, 1, 0, 0)

fun main() {
    // [2. 입력 스트림 생성]
    // System.in(키보드 입력)을 읽어들이는 BufferedReader를 만듭니다.
    val br = BufferedReader(InputStreamReader(System.`in`))

    // 첫 줄: 테스트 케이스의 개수 T를 읽어 정수로 변환합니다.
    val T = br.readLine().toInt()

    // 테스트 케이스(T) 횟수만큼 아래 로직을 반복 수행합니다.
    repeat(T) {
        // [3. 배추밭 정보 입력]
        // 한 줄을 읽어 공백(" ")을 기준으로 쪼갭니다. 예: "10 8 17"
        val st = StringTokenizer(br.readLine())

        // 순서대로 가로(M), 세로(N), 배추 개수(K)를 가져옵니다.
        val M = st.nextToken().toInt() // 밭의 가로 길이 (행의 개수로 사용됨)
        val N = st.nextToken().toInt() // 밭의 세로 길이 (열의 개수로 사용됨)
        val K = st.nextToken().toInt() // 심어진 배추의 총 개수

        // [4. 배추밭 지도(2차원 배열) 생성]
        // M행 N열 크기의 2차원 배열을 만듭니다.
        // 초기값은 IntArray의 기본값인 0으로 자동 채워집니다. (0: 배추 없음)
        val field = Array(M) { IntArray(N) }

        // [5. 배추 심기]
        // 배추 개수(K)만큼 반복하며 좌표를 입력받습니다.
        repeat(K) {
            val position = StringTokenizer(br.readLine())
            val x = position.nextToken().toInt()
            val y = position.nextToken().toInt()

            // 입력받은 좌표 (x, y)에 배추가 있다는 표시로 1을 대입합니다.
            field[x][y] = 1
        }

        // [6. 지렁이(연결된 배추 그룹) 개수 세기 시작]
        var worms = 0 // 필요한 배추흰지렁이 마리 수 (정답 변수)

        // 밭의 처음(0,0)부터 끝(M-1, N-1)까지 모든 칸을 하나씩 방문합니다.
        for (i in 0 until M) {      // 행(x) 순회
            for (j in 0 until N) {  // 열(y) 순회

                // 만약 현재 위치에 배추(1)가 있다면?
                // -> 아직 방문하지 않은 "새로운 배추 덩어리"를 발견한 것입니다.
                if (field[i][j] == 1) {

                    // 새로운 덩어리이므로 지렁이 한 마리가 필요합니다. 카운트 증가!
                    worms++

                    // [핵심 로직] DFS(깊이 우선 탐색) 실행
                    // 이 함수는 현재 발견된 배추와 "연결된 모든 배추"를 찾아서
                    // 전부 0으로 지워버리는(방문 처리) 역할을 합니다.
                    // 이렇게 해야 for문이 다음 배추를 검사할 때 중복해서 세지 않습니다.
                    dfs(field, i, j, M, N)
                }
            }
        }

        // 계산된 지렁이 총 마리 수를 출력합니다.
        println(worms)
    }
}

// [7. DFS 함수 (재귀 함수)]
// 역할: 시작점(x, y)과 연결된 모든 배추(1)를 찾아 0으로 바꿉니다.
fun dfs(field: Array<IntArray>, x: Int, y: Int, M: Int, N: Int) {

    // [방문 처리]
    // 현재 위치의 배추를 뽑습니다(0으로 변경).
    // 이제 이 배추는 '이미 샌 배추'가 됩니다.
    field[x][y] = 0

    // [4방향 탐색]
    // 상, 하, 좌, 우 4번 반복합니다.
    for (i in 0 until 4) {

        // 이동할 다음 좌표(nx, ny)를 계산합니다.
        // dx[i], dy[i]를 현재 좌표에 더해줍니다.
        val nx = x + dx[i]
        val ny = y + dy[i]

        // [유효성 검사 - 중요]
        // 1. nx가 0 이상이고 M 미만이어야 함 (행 범위 체크)
        // 2. ny가 0 이상이고 N 미만이어야 함 (열 범위 체크)
        // 3. 그리고 이동할 위치(field[nx][ny])에 배추(1)가 있어야 함
        // 이 조건들을 모두 만족해야만 이동할 수 있습니다.
        if (nx in 0 until M && ny in 0 until N && field[nx][ny] == 1) {

            // 조건이 맞다면 그 좌표로 이동해서 다시 DFS를 실행합니다. (재귀 호출)
            // 이렇게 하면 연결된 끝까지 파고들어 가며 배추를 모두 0으로 만듭니다.
            dfs(field, nx, ny, M, N)
        }
    }
}